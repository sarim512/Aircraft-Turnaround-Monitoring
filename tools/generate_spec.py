@dataclass
class ParsedDoc:
    """Structured view of a docstring.

    Attributes:
        summary: First paragraph (joined into one line).
        description: Remaining free text before the first section heading.
        sections: Section name -> dedented text block.
    """

    summary: str = ""
    description: str = ""
    sections: Dict[str, str] = field(default_factory=dict)


@dataclass
class ParamSpec:
    """One function parameter.

    Attributes:
        name: Parameter name (with ``*``/``**`` prefix when variadic).
        annotation: Unparsed type annotation or ``-``.
        default: Unparsed default or ``(required)``.
        description: Text from the ``Args:`` section.
    """

    name: str
    annotation: str
    default: str
    description: str


@dataclass
class FunctionSpec:
    """Everything the spec says about one function/method.

    Attributes:
        qualname: Dotted name inside the module (``Class.method`` or ``outer.inner``).
        signature: Full ``def`` line without decorators or body.
        decorators: Unparsed decorators.
        doc: Parsed docstring.
        params: Parameter specs (self/cls excluded).
        returns: Unparsed return annotation.
        calls: Auto-detected callee names.
        raises: Auto-detected raised exception names.
        body_source: Normalised statements (docstring excluded) when the body is short and no Logic is documented.
        body_lines: Number of source lines of the body without the docstring.
        nested: Nested function specs.
    """

    qualname: str
    signature: str
    decorators: List[str]
    doc: ParsedDoc
    params: List[ParamSpec]
    returns: str
    calls: List[str]
    raises: List[str]
    body_source: Optional[str]
    body_lines: int
    nested: List["FunctionSpec"] = field(default_factory=list)


@dataclass
class FieldSpec:
    """A class-level annotated attribute (dataclass field).

    Attributes:
        name: Field name.
        annotation: Unparsed annotation.
        default: Unparsed default or ``(required)``.
        description: Text from the class ``Attributes:`` section.
    """

    name: str
    annotation: str
    default: str
    description: str


@dataclass
class ClassSpec:
    """Everything the spec says about one class.

    Attributes:
        name: Class name.
        bases: Unparsed base classes.
        decorators: Unparsed decorators.
        doc: Parsed docstring.
        fields: Annotated attributes.
        members: Enum members as (name, value, description).
        methods: Method specs.
    """

    name: str
    bases: List[str]
    decorators: List[str]
    doc: ParsedDoc
    fields: List[FieldSpec]
    members: List[Tuple[str, str, str]]
    methods: List[FunctionSpec]


@dataclass
class ModuleSpec:
    """Everything the spec says about one Python file.

    Attributes:
        path: Repository-relative path (posix).
        doc: Parsed module docstring.
        imports: Normalised import statements.
        constants: Module-level assignments as (name, annotation, value).
        functions: Top-level function specs.
        classes: Class specs.
        is_test: True for files under tests/.
        light: True for files rendered in compact mode (tests and tools).
    """

    path: str
    doc: ParsedDoc
    imports: List[str]
    constants: List[Tuple[str, str, str]]
    functions: List[FunctionSpec]
    classes: List[ClassSpec]
    is_test: bool = False
    light: bool = False


def parse_docstring(doc: Optional[str]) -> ParsedDoc:
    """Split a docstring into summary, description and named sections.

    Args:
        doc: Raw docstring (or None).
    Returns:
        ParsedDoc; empty when ``doc`` is falsy.
    Logic:
        Dedent with ``inspect.cleandoc`` semantics; walk the lines, switching the current target whenever a
        line equals one of SECTION_NAMES followed by a colon; the text before the first heading is split into
        the first paragraph (summary) and the rest (description).
    """
    if not doc:
        return ParsedDoc()
    import inspect

    lines = inspect.cleandoc(doc).splitlines()
    head: List[str] = []
    sections: Dict[str, List[str]] = {}
    current: Optional[str] = None
    for line in lines:
        match = SECTION_RE.match(line.strip()) if not line.startswith((" ", "\t")) else None
        if match:
            current = match.group(1)
            sections.setdefault(current, [])
        elif current is None:
            head.append(line)
        else:
            sections[current].append(line)
    paragraphs = "\n".join(head).strip().split("\n\n", 1)
    summary = " ".join(paragraphs[0].split())
    description = paragraphs[1].strip() if len(paragraphs) > 1 else ""
    return ParsedDoc(summary, description, {k: textwrap.dedent("\n".join(v)).strip() for k, v in sections.items()})


def parse_named_items(block: str) -> Dict[str, str]:
    """Parse ``name: description`` lines with indented continuation lines.

    Args:
        block: Text of an ``Args:`` or ``Attributes:`` section.
    Returns:
        Mapping name -> single-line description.
    """
    items: Dict[str, str] = {}
    current: Optional[str] = None
    for raw in block.splitlines():
        if not raw.strip():
            continue
        if not raw.startswith((" ", "\t")) and ":" in raw:
            name, _, rest = raw.partition(":")
            current = name.strip().strip("`").lstrip("*")
            items[current] = rest.strip()
        elif current is not None:
            items[current] += " " + raw.strip()
    return items


def _dotted(node: ast.AST) -> Optional[str]:
    """Dotted name of a call target.

    Args:
        node: ``Call.func`` node.
    Returns:
        ``a.b.c`` for attribute chains rooted at a Name, ``...attr`` when the root is an expression, or None.
    """
    parts: List[str] = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    if isinstance(node, ast.Name):
        parts.append(node.id)
        return ".".join(reversed(parts))
    if parts:
        return "..." + ".".join(reversed(parts))
    return None


def _collect_calls_and_raises(func: ast.AST) -> Tuple[List[str], List[str]]:
    """Detect callees and raised exceptions inside a function (nested functions excluded).

    Args:
        func: FunctionDef node.
    Returns:
        (calls, raises), each de-duplicated in first-seen order. Builtins and trivial container/string
        methods, logging and Streamlit widget calls are filtered out; calls that merely construct a raised
        exception are not listed as calls.
    Logic:
        Define a recursive ``visit`` that skips nested function/lambda/class bodies. For ``Raise`` nodes record
        the exception name (or ``(re-raise)``) and remember the exception-constructing Call so it is not listed
        as a call. For other ``Call`` nodes record the dotted callee unless it is a builtin or a trivial
        container/string method. Finally de-duplicate both lists preserving first-seen order.
    """
    calls: List[str] = []
    raises: List[str] = []
    skip_calls: set = set()
    builtin_names = set(dir(builtins))

    def visit(node: ast.AST) -> None:
        """Recursive AST walker appending to the enclosing ``calls``/``raises`` lists.

        Args:
            node: AST node whose children are inspected.
        Logic:
            For every child: skip nested definitions; record Raise targets; record Call targets that pass the
            filters; recurse into the child.
        """
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda, ast.ClassDef)):
                continue
            if isinstance(child, ast.Raise):
                if child.exc is None:
                    raises.append("(re-raise)")
                else:
                    target = child.exc.func if isinstance(child.exc, ast.Call) else child.exc
                    name = _dotted(target)
                    if name:
                        raises.append(name)
                    if isinstance(child.exc, ast.Call):
                        skip_calls.add(id(child.exc))
            if isinstance(child, ast.Call) and id(child) not in skip_calls:
                name = _dotted(child.func)
                if (name and name.split(".")[-1] not in IGNORED_CALL_ATTRS and name not in builtin_names
                        and not name.startswith(IGNORED_CALL_PREFIXES)):
                    calls.append(name)
            visit(child)

    visit(func)
    dedupe = lambda seq: list(dict.fromkeys(seq))
    return dedupe(calls), dedupe(raises)


def _describe_function(node: ast.FunctionDef, prefix: str, is_method: bool) -> FunctionSpec:
    """Build a FunctionSpec from an AST node (recursing into nested functions).

    Args:
        node: FunctionDef.
        prefix: Qualified-name prefix (``Class.`` or ``outer.``).
        is_method: True to drop the first parameter (self/cls) from the parameter table.
    Returns:
        FunctionSpec.
    Logic:
        Parse docstring; collect parameters with annotations/defaults and descriptions from ``Args:``;
        compute the body (without docstring) line count; keep a normalised body only for short functions
        without a ``Logic:`` section; recurse into directly nested FunctionDefs.
    """
    doc = parse_docstring(ast.get_docstring(node, clean=False))
    arg_docs = parse_named_items(doc.sections.get("Args", ""))
    a = node.args
    positional = list(a.posonlyargs) + list(a.args)
    defaults: Dict[str, str] = {}
    for arg, dflt in zip(positional[len(positional) - len(a.defaults):], a.defaults):
        defaults[arg.arg] = ast.unparse(dflt)
    for arg, dflt in zip(a.kwonlyargs, a.kw_defaults):
        if dflt is not None:
            defaults[arg.arg] = ast.unparse(dflt)
    params: List[ParamSpec] = []

    def add(arg: ast.arg, prefix_chars: str = "") -> None:
        """Append one ParamSpec to the enclosing ``params`` list.

        Args:
            arg: AST argument node.
            prefix_chars: ``*`` or ``**`` for variadic parameters.
        """
        params.append(ParamSpec(prefix_chars + arg.arg, ast.unparse(arg.annotation) if arg.annotation else "-",
                                defaults.get(arg.arg, "(required)"), arg_docs.get(arg.arg, "")))

    for i, arg in enumerate(positional):
        if is_method and i == 0 and arg.arg in ("self", "cls"):
            continue
        add(arg)
    if a.vararg:
        add(a.vararg, "*")
    for arg in a.kwonlyargs:
        add(arg)
    if a.kwarg:
        add(a.kwarg, "**")
    body = node.body[1:] if ast.get_docstring(node, clean=False) is not None else node.body
    body_lines = (max((getattr(s, "end_lineno", s.lineno) for s in body), default=node.lineno) - body[0].lineno + 1) if body else 0
    body_source: Optional[str] = None
    if "Logic" not in doc.sections and 0 < body_lines <= TRIVIAL_BODY_LINES:
        body_source = "\n".join(ast.unparse(stmt) for stmt in body)
    calls, raises = _collect_calls_and_raises(node)
    header = next(line for line in ast.unparse(node).splitlines() if line.startswith("def "))
    nested = [_describe_function(n, f"{prefix}{node.name}.", False) for n in body if isinstance(n, ast.FunctionDef)]
    return FunctionSpec(
        qualname=f"{prefix}{node.name}",
        signature=header.rstrip(":"),
        decorators=[ast.unparse(d) for d in node.decorator_list],
        doc=doc,
        params=params,
        returns=ast.unparse(node.returns) if node.returns else "-",
        calls=calls,
        raises=raises,
        body_source=body_source,
        body_lines=body_lines,
        nested=nested,
    )


def _describe_class(node: ast.ClassDef) -> ClassSpec:
    """Build a ClassSpec from an AST node.

    Args:
        node: ClassDef.
    Returns:
        ClassSpec with fields (annotated attributes), enum members and methods.
    Logic:
        Parse the docstring and its ``Attributes:`` section; detect Enum classes from the base names; iterate the
        class body: annotated assignments become FieldSpecs (default = unparsed value or ``(required)``), plain
        assignments inside Enum classes become members, function definitions become method specs (self/cls
        dropped from their parameter tables).
    """
    doc = parse_docstring(ast.get_docstring(node, clean=False))
    attr_docs = parse_named_items(doc.sections.get("Attributes", ""))
    bases = [ast.unparse(b) for b in node.bases]
    is_enum = any("Enum" in b for b in bases)
    fields: List[FieldSpec] = []
    members: List[Tuple[str, str, str]] = []
    methods: List[FunctionSpec] = []
    for stmt in node.body:
        if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
            fields.append(FieldSpec(stmt.target.id, ast.unparse(stmt.annotation),
                                    ast.unparse(stmt.value) if stmt.value is not None else "(required)",
                                    attr_docs.get(stmt.target.id, "")))
        elif isinstance(stmt, ast.Assign) and is_enum:
            for target in stmt.targets:
                if isinstance(target, ast.Name):
                    members.append((target.id, ast.unparse(stmt.value), attr_docs.get(target.id, "")))
        elif isinstance(stmt, ast.FunctionDef):
            methods.append(_describe_function(stmt, f"{node.name}.", True))
    return ClassSpec(node.name, bases, [ast.unparse(d) for d in node.decorator_list], doc, fields, members, methods)


def describe_module(path: Path) -> ModuleSpec:
    """Parse one Python file into a ModuleSpec.

    Args:
        path: Absolute path of the file.
    Returns:
        ModuleSpec.
    Logic:
        Parse with ``ast``; collect import statements, module-level constants (skipping dunders other than
        ``__version__``), top-level functions and classes in source order.
    """
    rel = path.relative_to(REPO_ROOT).as_posix()
    tree = ast.parse(path.read_text(encoding="utf-8"))
    imports: List[str] = []
    constants: List[Tuple[str, str, str]] = []
    functions: List[FunctionSpec] = []
    classes: List[ClassSpec] = []
    for stmt in tree.body:
        if isinstance(stmt, (ast.Import, ast.ImportFrom)):
            imports.append(ast.unparse(stmt))
        elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
            constants.append((stmt.target.id, ast.unparse(stmt.annotation), ast.unparse(stmt.value) if stmt.value else ""))
        elif isinstance(stmt, ast.Assign):
            for target in stmt.targets:
                if isinstance(target, ast.Name) and (not target.id.startswith("__") or target.id == "__version__"):
                    constants.append((target.id, "-", ast.unparse(stmt.value)))
        elif isinstance(stmt, ast.FunctionDef):
            functions.append(_describe_function(stmt, "", False))
        elif isinstance(stmt, ast.ClassDef):
            classes.append(_describe_class(stmt))
    return ModuleSpec(rel, parse_docstring(ast.get_docstring(tree, clean=False)), imports, constants, functions, classes,
                      is_test=rel.startswith("tests/"), light=rel.startswith(("tests/", "tools/")))


def python_files() -> List[Path]:
    """All Python files of the repository in documentation order.

    Returns:
        Paths ordered by PYTHON_GROUP_ORDER, then alphabetically (``__init__.py`` first) inside a group.
    """
    files = [p for p in REPO_ROOT.rglob("*.py") if "__pycache__" not in p.parts and ".pytest_cache" not in p.parts]

    def key(path: Path) -> Tuple[int, int, str]:
        """Sort key: (group index, 0 for __init__.py else 1, relative path).

        Args:
            path: File path to rank.
        """
        rel = path.relative_to(REPO_ROOT).as_posix()
        group = next((i for i, g in enumerate(PYTHON_GROUP_ORDER) if rel == g or rel.startswith(g + "/")), len(PYTHON_GROUP_ORDER))
        return (group, 0 if path.name == "__init__.py" else 1, rel)

    return sorted(files, key=key)


def _cell(text: str) -> str:
    """Escape text for a Markdown table cell.

    Args:
        text: Raw text.
    Returns:
        Single-line text with pipes escaped and backticks around nothing.
    """
    return " ".join(text.split()).replace("|", "\\|")


def _code(text: str) -> str:
    """Wrap text in inline code safe for table cells.

    Args:
        text: Raw text.
    Returns:
        ``text`` in backticks with pipes escaped, or ``-`` when empty.
    """
    return f"`{_cell(text)}`" if text else "-"


def _indent_block(text: str, prefix: str = "  ") -> str:
    """Indent every non-empty line of a block.

    Args:
        text: Block of text.
        prefix: Indentation prefix.
    Returns:
        Indented text.
    """
    return "\n".join(prefix + line if line.strip() else line for line in text.splitlines())


def render_function(fn: FunctionSpec, light: bool = False, level: str = "#####") -> str:
    """Render one function/method as Markdown.

    Args:
        fn: Function spec.
        light: Compact rendering (used for test modules).
        level: Heading prefix.
    Returns:
        Markdown text including nested functions.
    Logic:
        Trivial accessors (no parameters, body of at most 3 lines, nothing documented beyond the summary) get a
        4-line compact entry. Otherwise emit heading, signature (+decorators), purpose and details. In full mode add: a parameter table (or
        "none"), the return annotation with its documented meaning, the ``Logic:`` text (or the normalised short
        body, or "see Purpose"), optional edge cases, then a dependency list (detected calls, detected and
        documented raises, documented side effects, notes). Recurse into nested functions.
    """
    out: List[str] = [f"{level} `{fn.qualname}`", ""]
    deco = f" (decorators: {', '.join('`@' + d + '`' for d in fn.decorators)})" if fn.decorators else ""
    compact = (not light and not fn.params and fn.body_source is not None and fn.body_lines <= 3
               and not fn.doc.description and "Side effects" not in fn.doc.sections and not fn.raises)
    if compact:
        ret = f"{_code(fn.returns)}" + (f" - {_cell(fn.doc.sections['Returns'])}" if "Returns" in fn.doc.sections else "")
        out.append(f"- **Signature**: `{fn.signature}`{deco}; **Parameters**: none; **Return Value**: {ret}")
        out.append(f"- **Purpose**: {fn.doc.summary or '(undocumented)'}")
        out.append("- **Internal Logic**: `" + fn.body_source.replace(chr(10), "; ") + "`")
        calls = ("Calls: " + ", ".join(f"`{c}`" for c in fn.calls) + "; ") if fn.calls else ""
        out.append(f"- **Dependencies & Side Effects**: {calls}no side effects")
        out.append("")
        return "\n".join(out)
    out.append(f"- **Signature**: `{fn.signature}`{deco}")
    out.append(f"- **Purpose**: {fn.doc.summary or '(undocumented)'}")
    if fn.doc.description:
        out.append(f"  - Details: {' '.join(fn.doc.description.split())}")
    if not light:
        if fn.params:
            out.append("- **Parameters**:")
            out.append("")
            out.append("  | Name | Type | Default | Description |")
            out.append("  |---|---|---|---|")
            for p in fn.params:
                out.append(f"  | `{p.name}` | {_code(p.annotation)} | {_code(p.default)} | {_cell(p.description) or '(undocumented)'} |")
            out.append("")
        else:
            out.append("- **Parameters**: none")
        ret_text = _cell(fn.doc.sections.get("Returns", ""))
        out.append(f"- **Return Value**: {_code(fn.returns)}" + (f" - {ret_text}" if ret_text else ""))
        out.append("- **Internal Logic & Algorithms**:")
        if "Logic" in fn.doc.sections:
            out.append(_indent_block(fn.doc.sections["Logic"]))
        elif fn.body_source:
            out.append("  Short body, reproduced in normalised form:")
            out.append("")
            out.append(_indent_block("```python\n" + fn.body_source + "\n```"))
        else:
            out.append("  (see Purpose)")
        if "Edge cases" in fn.doc.sections:
            out.append("  - Edge cases:")
            out.append(_indent_block(fn.doc.sections["Edge cases"], "    "))
        deps: List[str] = []
        if fn.calls:
            deps.append("Calls: " + ", ".join(f"`{c}`" for c in fn.calls))
        if fn.raises:
            deps.append("Raises (detected): " + ", ".join(f"`{r}`" for r in fn.raises))
        if "Raises" in fn.doc.sections:
            deps.append("Raises (documented): " + _cell(fn.doc.sections["Raises"]))
        deps.append("Side effects: " + (_cell(fn.doc.sections["Side effects"]) if "Side effects" in fn.doc.sections else "none documented (pure or in-memory only)"))
        if "Notes" in fn.doc.sections:
            deps.append("Notes: " + _cell(fn.doc.sections["Notes"]))
        out.append("- **Dependencies & Side Effects**:")
        out.extend(f"  - {d}" for d in deps)
    out.append("")
    for nested in fn.nested:
        out.append(render_function(nested, light, level))
    return "\n".join(out)


def render_class(cls: ClassSpec, light: bool = False) -> str:
    """Render one class as Markdown.

    Args:
        cls: Class spec.
        light: Compact rendering for method bodies (test modules).
    Returns:
        Markdown text including all methods.
    Logic:
        Emit heading with bases, decorators, purpose and details; an enum-member table and a field table when
        present; then render every method through ``render_function``.
    """
    bases = f"({', '.join(cls.bases)})" if cls.bases else ""
    out = [f"##### class `{cls.name}{bases}`", ""]
    if cls.decorators:
        out.append(f"- **Decorators**: {', '.join('`@' + d + '`' for d in cls.decorators)}")
    out.append(f"- **Purpose**: {cls.doc.summary or '(undocumented)'}")
    if cls.doc.description:
        out.append(f"  - Details: {' '.join(cls.doc.description.split())}")
    if cls.members:
        out += ["- **Enum members**:", "", "  | Member | Value | Meaning |", "  |---|---|---|"]
        out += [f"  | `{n}` | {_code(v)} | {_cell(d) or '(undocumented)'} |" for n, v, d in cls.members]
        out.append("")
    if cls.fields:
        out += ["- **Fields**:", "", "  | Name | Type | Default | Meaning |", "  |---|---|---|---|"]
        out += [f"  | `{f.name}` | {_code(f.annotation)} | {_code(f.default)} | {_cell(f.description) or '(undocumented)'} |" for f in cls.fields]
        out.append("")
    out.append("")
    for method in cls.methods:
        out.append(render_function(method, light))
    return "\n".join(out)


def _humanize(name: str) -> str:
    """Turn ``test_some_behaviour`` into ``Some behaviour``.

    Args:
        name: Function name.
    Returns:
        Capitalised sentence without the ``test_`` prefix.
    """
    text = name[5:] if name.startswith("test_") else name
    text = text.replace("_", " ").strip()
    return text[:1].upper() + text[1:]


def render_module(mod: ModuleSpec) -> str:
    """Render one Python file as Markdown.

    Args:
        mod: Module spec.
    Returns:
        Markdown text for Section 3 (file path, purpose, globals/imports, classes, functions).
    Logic:
        Emit file heading, primary purpose, imports and constants (values truncated at 200 chars). For tools
        (light, non-test) render classes and functions in compact mode. For test
        modules: render non-test classes/helpers in light mode and list test cases as ``name(fixtures) - summary``
        (docstring summary or humanised function name). For source modules: render every class then every
        function; emit a note when the file only contains a package marker.
    """
    out = [f"#### `{mod.path}`", "", f"**Primary purpose:** {mod.doc.summary or '(undocumented)'}"]
    if mod.doc.description:
        out += ["", " ".join(mod.doc.description.split())]
    out += ["", "**Global variables / constants / imports**", ""]
    out.append("- Imports: " + ("; ".join(f"`{i}`" for i in mod.imports) if mod.imports else "none"))
    if mod.constants:
        out.append("- Constants / globals:")
        for name, ann, value in mod.constants:
            shown = value if len(value) <= 200 else value[:197] + "..."
            out.append(f"  - `{name}`" + (f": `{ann}`" if ann != "-" else "") + (f" = `{_cell(shown)}`" if value else ""))
    else:
        out.append("- Constants / globals: none")
    out.append("")
    if mod.light and not mod.is_test:
        for cls in mod.classes:
            out.append(render_class(cls, light=True))
        for fn in mod.functions:
            out.append(render_function(fn, light=True))
        return "\n".join(out)
    if mod.is_test:
        helpers = [f for f in mod.functions if not f.qualname.startswith("test_")]
        tests = [f for f in mod.functions if f.qualname.startswith("test_")]
        tests += [m for c in mod.classes for m in c.methods if m.qualname.split(".")[-1].startswith("test_")]
        for cls in mod.classes:
            if not any(m.qualname.split(".")[-1].startswith("test_") for m in cls.methods):
                out.append(render_class(cls, light=True))
        for fn in helpers:
            out.append(render_function(fn, light=True))
        if tests:
            out.append("**Test cases**")
            out.append("")
            for fn in tests:
                params = ", ".join(p.name for p in fn.params)
                note = fn.doc.summary or _humanize(fn.qualname.split(".")[-1])
                out.append(f"- `{fn.qualname}({params})` - {note}")
            out.append("")
        return "\n".join(out)
    for cls in mod.classes:
        out.append(render_class(cls))
    for fn in mod.functions:
        out.append(render_function(fn))
    if not mod.classes and not mod.functions:
        out.append("_No classes or functions (package marker / constants only)._")
        out.append("")
    return "\n".join(out)


def render_data_files() -> str:
    """Render the non-Python files (configuration, schema, requirements, documentation).

    Returns:
        Markdown text; embedded files are shown verbatim in fenced blocks, documentation files get one line.
    Logic:
        For each entry of DATA_FILES that exists: print its heading and either its verbatim content in a fenced
        block or a pointer to Section 2.3 (schema). Then list DOC_FILES and the placeholder files.
    """
    out = ["#### Non-Python files", ""]
    for rel, lang, embed in DATA_FILES:
        path = REPO_ROOT / rel
        if not path.exists():
            continue
        out.append(f"##### `{rel}`")
        if embed:
            out += ["", f"```{lang}", path.read_text(encoding="utf-8").rstrip(), "```", ""]
        else:
            out += ["", "Embedded verbatim in Section 2.3 (database schema).", ""]
    out.append("##### Documentation files")
    out.append("")
    for rel, text in DOC_FILES.items():
        out.append(f"- `{rel}` - {text}")
    out += ["", "##### Placeholder files", "", "- `weights/.gitkeep`, `runtime/.gitkeep`, `data/.gitkeep` - keep empty runtime directories in version control (weights, live files and databases are git-ignored).", ""]
    return "\n".join(out)


def render_tree(modules: Sequence[ModuleSpec]) -> str:
    """Directory tree with a one-line purpose per file.

    Args:
        modules: All module specs.
    Returns:
        Markdown list in a fenced block.
    """
    lines = []
    for mod in modules:
        if mod.path.endswith("__init__.py") and not mod.doc.summary:
            continue
        lines.append(f"{mod.path:<58} {mod.doc.summary}")
    for rel, _, _ in DATA_FILES:
        if (REPO_ROOT / rel).exists():
            lines.append(f"{rel:<58} (data/config file)")
    for rel, text in DOC_FILES.items():
        lines.append(f"{rel:<58} {text}")
    return "```text\n" + "\n".join(lines) + "\n```"


def render_dependency_map(modules: Sequence[ModuleSpec]) -> str:
    """Internal import map of the ``turnaround`` package.

    Args:
        modules: All module specs.
    Returns:
        Markdown table: module -> internal modules it imports.
    """
    rows = ["| Module | Imports from (internal) |", "|---|---|"]
    for mod in modules:
        if not mod.path.startswith("src/turnaround/"):
            continue
        internal = sorted({re.sub(r"^from (turnaround[\w.]*) import .*$", r"\1", i) for i in mod.imports if i.startswith("from turnaround")})
        internal += sorted({i.replace("import ", "") for i in mod.imports if i.startswith("import turnaround")})
        if internal:
            rows.append(f"| `{mod.path.replace('src/', '').replace('.py', '').replace('/', '.')}` | " + ", ".join(f"`{m}`" for m in internal) + " |")
    return "\n".join(rows)


def render_config_reference() -> str:
    """Configuration key reference generated from the schema dataclasses.

    Returns:
        Markdown table of every YAML key (dotted path), type, default and meaning.
    Logic:
        Import ``turnaround.config.schema``; recurse through dataclass fields starting at AppConfig, using each
        class docstring's ``Attributes:`` section for descriptions and evaluating ``default_factory`` for defaults.
    """
    sys.path.insert(0, str(SRC_DIR))
    schema = importlib.import_module("turnaround.config.schema")
    import typing

    rows = ["| Key | Type | Default | Meaning |", "|---|---|---|---|"]

    def walk(cls, prefix: str) -> None:
        """Append rows for one dataclass, recursing into nested dataclasses.

        Args:
            cls: Dataclass type to describe.
            prefix: Dotted key prefix (``""`` for the root, ``"source."`` etc. when nested).
        Logic:
            Read descriptions from the class ``Attributes:`` section; for each field either recurse (nested
            dataclass) or append a row with the type text and the default (``default``, evaluated
            ``default_factory`` or ``(required)``).
        """
        attr_docs = parse_named_items(parse_docstring(cls.__doc__).sections.get("Attributes", ""))
        hints = typing.get_type_hints(cls)
        for f in dataclasses.fields(cls):
            hint = hints[f.name]
            key = f"{prefix}{f.name}"
            if dataclasses.is_dataclass(hint):
                walk(hint, key + ".")
                continue
            if f.default is not dataclasses.MISSING:
                default = repr(f.default)
            elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
                default = repr(f.default_factory())  # type: ignore[misc]
            else:
                default = "(required)"
            type_text = hint.__name__ if isinstance(hint, type) else str(hint).replace("typing.", "")
            rows.append(f"| `{key}` | {_code(type_text)} | {_code(default)} | {_cell(attr_docs.get(f.name, ''))} |")

    walk(schema.AppConfig, "")
    return "\n".join(rows)


def collect_problems(modules: Sequence[ModuleSpec]) -> List[str]:
    """Find documentation gaps (used by ``--strict`` and the docstring-coverage test).

    Args:
        modules: All module specs.
    Returns:
        Human-readable problems: missing module/class/function summaries, undocumented parameters, missing
        ``Logic:`` on non-trivial functions, undocumented dataclass fields / enum members. Test modules are
        only required to have a module summary and docstrings on their helper functions.
    Logic:
        Define ``check_function`` (summary present; every parameter of non-dunder functions described; bodies
        longer than TRIVIAL_BODY_LINES have a Logic section; recurse into nested functions). Then per module:
        require a module docstring; skip test modules; require class docstrings, dataclass field and enum member
        descriptions, and check every method and top-level function.
    """
    problems: List[str] = []

    def check_function(path: str, fn: FunctionSpec) -> None:
        """Check one function and its nested functions.

        Args:
            path: Repository-relative path used in problem messages.
            fn: Function spec to check.
        """
        where = f"{path}:{fn.qualname}"
        short = fn.qualname.split(".")[-1]
        if not fn.doc.summary:
            problems.append(f"{where}: missing docstring summary")
        is_dunder = short.startswith("__") and short.endswith("__") and short != "__init__"
        if not is_dunder:
            for p in fn.params:
                if not p.description:
                    problems.append(f"{where}: parameter '{p.name}' undocumented in Args")
            if fn.body_lines > TRIVIAL_BODY_LINES and "Logic" not in fn.doc.sections and "pass" != fn.body_source:
                problems.append(f"{where}: {fn.body_lines}-line body without a Logic section")
        for nested in fn.nested:
            check_function(path, nested)

    for mod in modules:
        if not mod.doc.summary:
            problems.append(f"{mod.path}: missing module docstring")
        if mod.is_test:
            helpers = [f for f in mod.functions if not f.qualname.startswith("test_")]
            helpers += [m for c in mod.classes for m in c.methods]
            problems += [f"{mod.path}:{f.qualname}: test helper without docstring" for f in helpers if not f.doc.summary]
            continue
        for cls in mod.classes:
            if not cls.doc.summary:
                problems.append(f"{mod.path}:{cls.name}: missing class docstring")
            is_data = any("dataclass" in d for d in cls.decorators)
            if is_data:
                problems += [f"{mod.path}:{cls.name}.{f.name}: field undocumented in Attributes" for f in cls.fields if not f.description]
            problems += [f"{mod.path}:{cls.name}.{n}: enum member undocumented" for n, _, d in cls.members if not d]
            for method in cls.methods:
                check_function(mod.path, method)
        for fn in mod.functions:
            check_function(mod.path, fn)
    return problems


def build_spec() -> Tuple[str, List[str]]:
    """Assemble the full specification text.

    Returns:
        (markdown, problems) where problems come from ``collect_problems``.
    Logic:
        Describe every Python file; fill the template placeholders ``{{FILE_TREE}}``, ``{{DEPENDENCY_MAP}}``,
        ``{{CONFIG_REFERENCE}}``, ``{{SQL_SCHEMA}}`` and ``{{FILE_SPECS}}``.
    """
    modules = [describe_module(p) for p in python_files()]
    template = TEMPLATE_PATH.read_text(encoding="utf-8")
    sql = (REPO_ROOT / "src/turnaround/storage/schema.sql").read_text(encoding="utf-8").rstrip()
    specs: List[str] = []
    current_group = ""
    group_no = 0
    for mod in modules:
        group = next((g for g in PYTHON_GROUP_ORDER if mod.path == g or mod.path.startswith(g + "/")), "other")
        if group != current_group:
            current_group = group
            group_no += 1
            specs.append(f"### 3.{group_no} Group: `{group}`\n")
        specs.append(render_module(mod))
    specs.append(render_data_files())
    replacements = {
        "{{FILE_TREE}}": render_tree(modules),
        "{{DEPENDENCY_MAP}}": render_dependency_map(modules),
        "{{CONFIG_REFERENCE}}": render_config_reference(),
        "{{SQL_SCHEMA}}": "```sql\n" + sql + "\n```",
        "{{FILE_SPECS}}": "\n".join(specs),
    }
    for marker, value in replacements.items():
        template = template.replace(marker, value)
    return template, collect_problems(modules)


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Command-line entry point.

    Args:
        argv: Argument list (None uses ``sys.argv[1:]``).
    Returns:
        0 on success; 1 when ``--strict`` finds documentation gaps or ``--check`` finds the committed spec stale.
    Logic:
        Build the spec and print every documentation gap to stderr. ``--strict`` returns 1 when gaps exist;
        ``--check`` compares with the committed file (returns 1 when different) and never writes; otherwise write
        the file and print its size.
    Side effects:
        Writes ``docs/PIPELINE_SPEC.md`` unless ``--check`` is given.
    """
    parser = argparse.ArgumentParser(description="Generate docs/PIPELINE_SPEC.md from the code base")
    parser.add_argument("--strict", action="store_true", help="Fail when docstrings are incomplete")
    parser.add_argument("--check", action="store_true", help="Do not write; fail if the committed spec is out of date")
    args = parser.parse_args(argv)
    text, problems = build_spec()
    for problem in problems:
        print(f"DOC GAP: {problem}", file=sys.stderr)
    if args.strict and problems:
        return 1
    if args.check:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        if current != text:
            print("docs/PIPELINE_SPEC.md is out of date; run: python tools/generate_spec.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT_PATH.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(REPO_ROOT)} ({len(text.splitlines())} lines, {len(problems)} doc gaps)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
